function resolveBase(rule, subject, eventDate) {
  const u = require(`${__hooks}/lib_util.js`);
  const rec = subject.record;
  let base = '';
  const lbl = BASE_LABEL[rule.base] || ['Base date', '起算日'];
  let label = u.bi(lbl[0], lbl[1]);
  if (rule.base === 'priority_date' && subject.type === 'matter') base = earliestPriority(rec);
  else if (rule.base !== 'event_date') {
    const map = BASE_FIELDS[subject.type] || {};
    const f = map[rule.base];
    if (f) base = u.d10(rec.getString(f));
  }
  if (base === '') {
    base = u.d10(eventDate);
    if (rule.base !== 'event_date') {
      label = u.bi(lbl[0] + ' (not recorded yet, event date used)', lbl[1] + '（未登録のため事象の日を使用）');
    } else label = u.bi('Event date', '事象の日');
  }
  return { date: base, label: label };
}

function offsetText(y, m, d, business) {
  const en = [];
  const ja = [];
  if (y) {
    en.push(y + (Math.abs(y) === 1 ? ' year' : ' years'));
    ja.push(y + '年');
  }
  if (m) {
    en.push(m + (Math.abs(m) === 1 ? ' month' : ' months'));
    ja.push(m + 'か月');
  }
  if (d) {
    en.push(d + (business ? ' working' : '') + (Math.abs(d) === 1 ? ' day' : ' days'));
    ja.push(d + (business ? '執務日' : '日'));
  }
  return { en: en.length ? en.join(', ') : 'no offset', ja: ja.length ? ja.join('') : 'なし' };
}

function fill(template, cycle, every) {
  const n0 = every ? cycle * every : cycle;
  return String(template || '').split('{n}').join(String(cycle)).split('{n0}').join(String(n0));
}

function cycleTitle(rule, cycle) {
  return { en: fill(rule.title, cycle, rule.every), ja: fill(rule.title_ja || rule.title, cycle, rule.every) };
}

function cycleLabel(rule, cycle) {
  if (!rule.cycle_label) return '';
  return fill(rule.cycle_label, cycle, rule.every);
}

function rollOfficeFor(app, rule, subject, eventData) {
  const u = require(`${__hooks}/lib_util.js`);
  if (rule.roll_office) return rule.roll_office;
  if (subject.type === 'matter' || subject.type === 'recordation') return subject.jurisdiction;
  if (eventData && eventData.jurisdiction) return String(eventData.jurisdiction).toUpperCase();
  if (rule.business) return String(u.setting(app, 'work_calendar', 'JP') || 'JP').toUpperCase();
  return '';
}

/**
 * Compute every date for one rule application.
 * overrides: { period_months, period_days, due_date } for office-set periods.
 */
function computeRule(app, rule, subject, eventDate, cycle, overrides, bufferDays, eventData) {
  const u = require(`${__hooks}/lib_util.js`);
  const cal = require(`${__hooks}/lib_calendar.js`);
  const ov = overrides || {};
  const baseInfo = resolveBase(rule, subject, eventDate);
  const base = baseInfo.date;
  if (base === '') return null;
  const steps = [];
  steps.push(u.bi(baseInfo.label.en + ': ' + u.human(base) + '.', baseInfo.label.ja + '：' + u.humanJa(base) + '。'));
  const office = rollOfficeFor(app, rule, subject, eventData);

  const recurring = rule.every > 0;
  const extraYears = recurring ? (cycle - rule.first) * rule.every : 0;
  let nominal = '';
  if (rule.kind === 'designated' && u.d10(ov.due_date) !== '') {
    nominal = u.d10(ov.due_date);
    steps.push(u.bi('The office set the due date in the communication: ' + u.human(nominal) + '.', '通知書で官庁が指定した期限：' + u.humanJa(nominal) + '。'));
  } else if (rule.kind === 'designated' && Number(ov.period_months) > 0) {
    nominal = u.addYMD(base, 0, Number(ov.period_months), 0);
    steps.push(u.bi(
      'Period set by the office: ' + ov.period_months + ' months from the base date gives ' + u.human(nominal) + '.',
      '官庁指定の期間：起算日から' + ov.period_months + 'か月で' + u.humanJa(nominal) + '。',
    ));
  } else if (rule.kind === 'designated' && Number(ov.period_days) > 0) {
    nominal = u.addDays(base, Number(ov.period_days));
    steps.push(u.bi(
      'Period set by the office: ' + ov.period_days + ' days from the base date gives ' + u.human(nominal) + '.',
      '官庁指定の期間：起算日から' + ov.period_days + '日で' + u.humanJa(nominal) + '。',
    ));
  } else {
    const off = offsetText(rule.oy + extraYears, rule.om, rule.od, rule.business);
    if (rule.business && rule.od !== 0) {
      const mid = u.addYMD(base, rule.oy + extraYears, rule.om, 0);
      const bd = cal.addBusinessDays(app, office, mid, rule.od);
      nominal = bd.date;
      steps.push(u.bi(
        'Rule ' + rule.code + ' (v' + rule.version + '): ' + off.en + ' from the base date.',
        'ルール ' + rule.code + '（第' + rule.version + '版）：起算日から' + off.ja + '。',
      ));
      for (const s of bd.steps) steps.push(s);
    } else {
      nominal = u.addYMD(base, rule.oy + extraYears, rule.om, rule.od);
      const usual = rule.kind === 'designated';
      steps.push(u.bi(
        'Rule ' + rule.code + ' (v' + rule.version + '): ' + off.en + (rule.oy + rule.om + rule.od < 0 ? ' before' : ' after') + ' the base date gives ' + u.human(nominal) + '.' +
          (usual ? ' This is the usual period; confirm it against the communication.' : ''),
        'ルール ' + rule.code + '（第' + rule.version + '版）：起算日' + (rule.oy + rule.om + rule.od < 0 ? 'の' : 'から') + off.ja + (rule.oy + rule.om + rule.od < 0 ? '前' : '後') + 'は' + u.humanJa(nominal) + '。' +
          (usual ? '通常の期間です。通知書の記載を確認してください。' : ''),
      ));
    }
  }
  if (rule.eom) {
    const eom = u.endOfMonth(nominal);
    if (eom !== nominal) steps.push(u.bi('Due on the last day of that month: ' + u.human(eom) + '.', 'その月の末日が期限：' + u.humanJa(eom) + '。'));
    nominal = eom;
  }

  let due = nominal;
  if (STATUTORY[rule.kind] && office !== '' && office !== '*' && !rule.business) {
    const rolled = cal.rollForward(app, office, nominal);
    if (rolled.date !== nominal) {
      for (const s of rolled.steps) steps.push(s);
      steps.push(u.bi(
        'Moves to the next day the ' + cal.officeName(office) + ' is open: ' + u.human(rolled.date) + '.',
        cal.officeNameJa(office) + 'の次の開庁日に繰り延べ：' + u.humanJa(rolled.date) + '。',
      ));
      due = rolled.date;
    } else {
      steps.push(u.bi(
        u.human(nominal) + ' is a ' + u.weekdayName(nominal) + ' and the ' + cal.officeName(office) + ' is open, so the date stands.',
        u.humanJa(nominal) + 'は' + u.weekdayNameJa(nominal) + 'で' + cal.officeNameJa(office) + 'は開庁しているため、この日が期限です。',
      ));
    }
  }

  let finalDate = '';
  if (rule.kind === 'extendable' || rule.kind === 'designated') {
    let finalNominal = '';
    if (rule.final_offset_months > 0) finalNominal = u.addYMD(base, extraYears, rule.final_offset_months, 0);
    else if (rule.final_offset_days > 0) {
      finalNominal = rule.business ? cal.addBusinessDays(app, office, base, rule.final_offset_days).date : u.addDays(base, rule.final_offset_days);
    } else if (rule.extensions.length > 0) {
      const last = rule.extensions[rule.extensions.length - 1];
      if (Number(last.days) > 0) finalNominal = rule.business ? cal.addBusinessDays(app, office, nominal, Number(last.days)).date : u.addDays(nominal, Number(last.days));
      else finalNominal = u.addYMD(nominal, 0, Number(last.months) || 0, 0);
    }
    if (finalNominal !== '') {
      finalDate = office !== '' && !rule.business ? cal.rollForward(app, office, finalNominal).date : finalNominal;
      const labels = rule.extensions.map(function (x) {
        return x.label;
      });
      const labelsJa = rule.extensions.map(function (x) {
        return x.label_ja || x.label;
      });
      steps.push(u.bi(
        'Extendable to ' + u.human(finalDate) + (labels.length ? ' (' + labels.join('; ') + ').' : '.'),
        u.humanJa(finalDate) + 'まで延長可能' + (labelsJa.length ? '（' + labelsJa.join('、') + '）。' : '。'),
      ));
    }
  } else if (rule.final_offset_days > 0) {
    finalDate = rule.business ? cal.addBusinessDays(app, office, base, rule.final_offset_days).date : u.addDays(base, rule.final_offset_days);
  }
  if (finalDate !== '' && rule.kind === 'hard' && rule.final_offset_days > 0) {
    steps.push(u.bi('The window closes on ' + u.human(finalDate) + '.', '期間の最終日：' + u.humanJa(finalDate) + '。'));
  }

  // Window and grace run from the statutory (nominal) date, not the rolled one:
  // rolling first would push the grace end past the real last day.
  const windowOpens = rule.window_months > 0 ? u.addYMD(nominal, 0, -rule.window_months, 0) : '';
  if (windowOpens !== '') steps.push(u.bi('Can be filed or paid from ' + u.human(windowOpens) + '.', u.humanJa(windowOpens) + 'から手続・納付が可能。'));

  let graceEnd = '';
  if (rule.grace_months > 0) {
    const g = u.addYMD(nominal, 0, rule.grace_months, 0);
    graceEnd = office !== '' ? cal.rollForward(app, office, g).date : g;
    steps.push(u.bi(
      'Grace period ends ' + u.human(graceEnd) + '.' + (rule.grace_note ? ' ' + rule.grace_note : ''),
      '猶予期間の満了：' + u.humanJa(graceEnd) + '。',
    ));
  }

  let target = due;
  const buffer = Number(bufferDays) > 0 ? Number(bufferDays) : 0;
  if (STATUTORY[rule.kind] && buffer > 0 && !rule.business) {
    target = u.addDays(due, -buffer);
    if (windowOpens !== '' && target < windowOpens) target = windowOpens;
    if (target < base) target = base;
    steps.push(u.bi(
      'Target date set ' + buffer + ' days before the due date (organization setting).',
      '社内目標日は期限の' + buffer + '日前（組織設定）。',
    ));
  }

  return {
    base_date: base,
    base_label: baseInfo.label,
    nominal: nominal,
    due: due,
    target: target,
    final: finalDate,
    window_opens: windowOpens,
    grace_end: graceEnd,
    steps: steps,
    office: office,
  };
}

