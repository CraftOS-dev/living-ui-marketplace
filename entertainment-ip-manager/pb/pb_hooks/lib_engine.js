/** A title with a publication date records WORK_PUBLISHED (US 412 reminder and terms). */
function syncWork(app, work, actorId) {
  const u = require(`${__hooks}/lib_util.js`);
  const pub = u.d10(work.getString('publication_date'));
  if (pub === '') return { created: 0 };
  return ensureSystemEvent(app, subjectFromRecord('work', work), 'WORK_PUBLISHED', pub, actorId);
}

/** Author grants: Section 203 termination windows run from the grant date. */
function syncAuthorGrant(app, agr, actorId) {
  const u = require(`${__hooks}/lib_util.js`);
  if (!agr.getBool('author_grant')) return { created: 0 };
  const signed = u.d10(agr.getString('signed_date'));
  if (signed === '') return { created: 0 };
  return ensureSystemEvent(app, subjectFromRecord('agreement', agr), 'AUTHOR_GRANT_EXECUTED', signed, actorId, { jurisdiction: 'US' });
}

/** Talent dates drive the debut and graduation playbooks. */
function syncTalent(app, talent, actorId) {
  const u = require(`${__hooks}/lib_util.js`);
  const subject = subjectFromRecord('talent', talent);
  const out = { created: 0, moved: 0 };
  const debut = u.d10(talent.getString('debut_date'));
  const life = talent.getString('lifecycle');
  if (debut !== '' && (life === 'audition' || life === 'pre_debut' || life === '') && debut >= u.today()) {
    const r = ensureSystemEvent(app, subject, 'DEBUT_SCHEDULED', u.today() < debut ? u.today() : debut, actorId);
    out.created += r.created;
    if (r.created === 0) {
      const g = regenerate(app, subject, true, actorId);
      out.moved += g.moved.length;
    }
  }
  const grad = u.d10(talent.getString('graduation_date'));
  if (grad !== '' && (life === 'graduation_announced' || life === 'active' || life === 'hiatus')) {
    const evs = u.findMany(app, 'events', 'talent = {:t} && code = "GRADUATION_SCHEDULED"', '', 0, { t: talent.id });
    if (evs.length === 0) {
      const r = recordEvent(app, subject, 'GRADUATION_SCHEDULED', u.today() < grad ? u.today() : grad, { source: 'system', actorId: actorId });
      out.created += r.created.length;
    } else {
      const g = regenerate(app, subject, true, actorId);
      out.moved += g.moved.length;
    }
  }
  return out;
}

/** Customs recordations: the accepted event drives the renewal rule from valid_until. */
function syncRecordation(app, rec, actorId) {
  const u = require(`${__hooks}/lib_util.js`);
  const accepted = u.d10(rec.getString('accepted_date'));
  if (accepted === '' || u.d10(rec.getString('valid_until')) === '') return { created: 0 };
  const subject = subjectFromRecord('recordation', rec);
  const r = ensureSystemEvent(app, subject, 'RECORDATION_ACCEPTED', accepted, actorId, { jurisdiction: rec.getString('jurisdiction') });
  if (r.created === 0) regenerate(app, subject, true, actorId);
  return r;
}

