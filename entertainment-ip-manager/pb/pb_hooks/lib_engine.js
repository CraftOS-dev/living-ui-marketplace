/** Statutory expiry for a trademark or design: { date, text: { en, ja } }. */
function computeExpiry(app, matter) {
  const u = require(`${__hooks}/lib_util.js`);
  const t = matter.getString('ip_type');
  const cc = matter.getString('jurisdiction').toUpperCase();
  const filing = u.d10(matter.getString('filing_date'));
  const reg = u.d10(matter.getString('registration_date'));
  if (t === 'design') {
    if (cc === 'US') {
      if (reg === '') return { date: '', text: u.bi('US design term runs 15 years from grant.', '米国の意匠は登録から15年です。') };
      return { date: u.addYMD(reg, 15, 0, 0), text: u.bi('15 years from grant (35 U.S.C. 173).', '登録から15年（35 U.S.C. 173）。') };
    }
    if (filing === '') return { date: '', text: u.bi('Needs a filing date.', '出願日が必要です。') };
    const years = { JP: 25, EM: 25, CN: 15, KR: 20, TW: 15 }[cc] || 25;
    const cite = {
      JP: 'JP Design Act Art. 21(1)',
      EM: 'Reg. (EC) 6/2002 Art. 12',
      CN: 'CN Patent Law Art. 42 (designs filed from 1 June 2021)',
      KR: 'KR Design Protection Act Art. 91',
      TW: 'TW Patent Act Art. 135',
    }[cc] || 'national law';
    return {
      date: u.addYMD(filing, years, 0, 0),
      text: u.bi(
        'Maximum ' + years + ' years from filing, subject to renewals or annual fees (' + cite + ').',
        '出願から最長' + years + '年（更新・年金の納付が条件、' + cite + '）。',
      ),
    };
  }
  if (t === 'trademark') {
    const k = renewalCount(app, matter.id) + 1;
    const renewed = k > 1 ? ' (' + (k - 1) + ' renewal(s) recorded).' : '.';
    const renewedJa = k > 1 ? '（更新' + (k - 1) + '回記録済み）。' : '。';
    if (cc === 'EM') {
      if (filing === '') return { date: '', text: u.bi('EU trade marks run 10 years from filing.', 'EU商標は出願から10年です。') };
      return {
        date: u.addYMD(filing, 10 * k, 0, 0),
        text: u.bi('10 years from filing, renewable every 10 years' + renewed, '出願から10年、10年ごとに更新可能' + renewedJa),
      };
    }
    if (reg === '') return { date: '', text: u.bi('The term starts at registration.', '存続期間は登録日から始まります。') };
    return {
      date: u.addYMD(reg, 10 * k, 0, 0),
      text: u.bi('10 years from registration, renewable every 10 years' + renewed, '登録から10年、10年ごとに更新可能' + renewedJa),
    };
  }
  return { date: '', text: u.bi('', '') };
}

const FILM_TYPES = ['series', 'season', 'episode', 'film', 'ova', 'special', 'short', 'stream', 'stream_archive', 'music_video'];

/** Copyright term under US, Japanese and EU law for a title: { US, JP, EU } each { date, text: { en, ja }, flags }. */
function copyrightTerms(work) {
  const u = require(`${__hooks}/lib_util.js`);
  const pub = u.d10(work.getString('publication_date'));
  const created = u.d10(work.getString('creation_date'));
  const death = work.getInt('author_death_year');
  const tt = work.getString('title_type');
  const film = FILM_TYPES.indexOf(tt) >= 0 || work.getString('author_kind') === 'film';
  const kind = work.getString('author_kind') || (work.getBool('made_for_hire') ? 'corporate' : film ? 'film' : 'individual');
  const out = {};
  function endOfYear(y) {
    return y + '-12-31';
  }
  const flags = [];
  if (pub !== '' && pub < '1971-01-01' && film) {
    flags.push(u.bi(
      'Published before 1971: the old Copyright Act may give a longer term (author death + 38 years). Check case by case.',
      '1971年以前の公表：旧著作権法により保護期間が長くなる場合があります（著作者の死後38年）。個別に確認してください。',
    ));
  }
  // United States (17 U.S.C. 302, 305: terms run to the end of the calendar year).
  if (work.getBool('made_for_hire') || kind === 'corporate' || kind === 'anonymous' || kind === 'film') {
    const a = pub ? Number(pub.slice(0, 4)) + 95 : 0;
    const b = created ? Number(created.slice(0, 4)) + 120 : 0;
    const y = a && b ? Math.min(a, b) : a || b;
    out.US = y
      ? {
          date: endOfYear(y),
          text: u.bi(
            '95 years from publication or 120 years from creation, whichever ends first, if a work made for hire (17 U.S.C. 302(c)). Whether a Japanese title is a US work made for hire depends on the facts.',
            '職務著作の場合、発行から95年または創作から120年の早い方（17 U.S.C. 302(c)）。日本の作品が米国の職務著作に当たるかは事実関係によります。',
          ),
        }
      : { date: '', text: u.bi('Needs a publication or creation date.', '公表日または創作日が必要です。') };
  } else if (death > 0) {
    out.US = {
      date: endOfYear(death + 70),
      text: u.bi(
        'Life of the ' + (kind === 'joint' ? 'last surviving author' : 'author') + ' plus 70 years (17 U.S.C. 302(a), (b)).',
        (kind === 'joint' ? '最後に死亡した著作者' : '著作者') + 'の死後70年（17 U.S.C. 302(a), (b)）。',
      ),
    };
  } else {
    out.US = { date: '', text: u.bi('Life of the author plus 70 years. Enter the author death year when known.', '著作者の死後70年。判明したら死亡年を入力してください。') };
  }
  // Japan (Copyright Act Art. 51-54, 56, 57: counted from 1 January of the following year).
  if (film) {
    out.JP = pub
      ? {
          date: endOfYear(Number(pub.slice(0, 4)) + 70),
          text: u.bi(
            'Cinematographic works: 70 years from publication (Art. 54(1)). Episodes released in instalments are timed one by one (Art. 56). When the film\'s term ends, the original work\'s copyright for use in that film ends too (Art. 54(2)).',
            '映画の著作物：公表後70年（54条1項）。回を追って公表される作品は各回ごとに計算（56条）。映画の保護期間が終わると、その映画の利用に関する原作の著作権も消滅（54条2項）。',
          ),
          flags: flags,
        }
      : { date: '', text: u.bi('Cinematographic works: 70 years from publication (Art. 54).', '映画の著作物：公表後70年（54条）。'), flags: flags };
  } else if (kind === 'corporate' || work.getBool('made_for_hire') || kind === 'anonymous') {
    const y = pub ? Number(pub.slice(0, 4)) : created ? Number(created.slice(0, 4)) : 0;
    out.JP = y
      ? {
          date: endOfYear(y + 70),
          text: u.bi('Works under a corporate or anonymous name: 70 years from publication (Art. 52, 53).', '団体名義・無名の著作物：公表後70年（52条、53条）。'),
          flags: flags,
        }
      : { date: '', text: u.bi('Needs a publication date.', '公表日が必要です。'), flags: flags };
  } else if (death > 0) {
    out.JP = { date: endOfYear(death + 70), text: u.bi('Life of the author plus 70 years (Art. 51, 57).', '著作者の死後70年（51条、57条）。'), flags: flags };
  } else {
    out.JP = {
      date: '',
      text: u.bi('Life of the author plus 70 years. Enter the author death year when known.', '著作者の死後70年。判明したら死亡年を入力してください。'),
      flags: flags,
    };
  }
  // European Union (Directive 2006/116/EC).
  if (death > 0 && kind !== 'anonymous') {
    out.EU = {
      date: endOfYear(death + 70),
      text: film
        ? u.bi(
            '70 years after the death of the last of the principal director, screenwriter, dialogue author and composer (Art. 2(2)). Enter the latest death year. Non-EU works never exceed the country-of-origin term (Art. 7(1)).',
            '主たる監督、脚本家、台詞作者、作曲家のうち最後に死亡した者の死後70年（2条2項）。最も遅い死亡年を入力してください。EU域外の作品は本国の保護期間を超えません（7条1項）。',
          )
        : u.bi('Life of the author plus 70 years (Art. 1).', '著作者の死後70年（1条）。'),
    };
  } else if (pub && (kind === 'anonymous' || kind === 'corporate' || work.getBool('made_for_hire'))) {
    out.EU = {
      date: endOfYear(Number(pub.slice(0, 4)) + 70),
      text: u.bi('Anonymous or pseudonymous works: 70 years from lawful publication (Art. 1(3)).', '無名・変名の著作物：適法な公表後70年（1条3項）。'),
    };
  } else {
    out.EU = {
      date: '',
      text: u.bi('Life of the author plus 70 years. Enter the author death year when known.', '著作者の死後70年。判明したら死亡年を入力してください。'),
    };
  }
  return out;
}

function refreshMatterSummary(app, matterId) {
  const u = require(`${__hooks}/lib_util.js`);
  const m = u.byId(app, 'matters', matterId);
  if (m === null) return;
  const open = u.findMany(app, 'deadlines', 'matter = {:m} && status = "open"', 'due_date', 1, { m: matterId });
  const next = open.length ? u.d10(open[0].getString('due_date')) : '';
  const nextTitle = open.length ? open[0].getString('title') : '';
  const nextTitleJa = open.length ? open[0].getString('title_ja') : '';
  let changed = false;
  if (u.d10(m.getString('next_deadline')) !== next) {
    m.set('next_deadline', u.toPb(next));
    changed = true;
  }
  if (m.getString('next_deadline_title') !== nextTitle) {
    m.set('next_deadline_title', nextTitle);
    changed = true;
  }
  if (m.getString('next_deadline_title_ja') !== nextTitleJa) {
    m.set('next_deadline_title_ja', nextTitleJa);
    changed = true;
  }
  if (!m.getBool('expiry_override')) {
    const exp = computeExpiry(app, m).date;
    if (u.d10(m.getString('expiry_date')) !== exp) {
      m.set('expiry_date', u.toPb(exp));
      changed = true;
    }
  }
  if (changed) app.save(m);
}

