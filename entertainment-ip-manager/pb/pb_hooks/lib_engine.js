function subjectOf(app, type, id) {
  const u = require(`${__hooks}/lib_util.js`);
  const def = SUBJECTS[type];
  if (!def) return null;
  const rec = u.byId(app, def.coll, id);
  if (rec === null) return null;
  return subjectFromRecord(type, rec);
}

function subjectFromRecord(type, rec) {
  const s = {
    type: type,
    id: rec.id,
    record: rec,
    subject_type: type,
    jurisdiction: '*',
    route: '',
    label: '',
  };
  switch (type) {
    case 'matter':
      s.subject_type = rec.getString('ip_type');
      s.jurisdiction = rec.getString('jurisdiction').toUpperCase();
      s.route = rec.getString('route');
      s.label = rec.getString('ref') || rec.getString('title');
      break;
    case 'agreement':
      s.label = rec.getString('ref') || rec.getString('title');
      break;
    case 'work':
      s.jurisdiction = rec.getString('publication_country').toUpperCase() || '*';
      s.label = rec.getString('title');
      break;
    case 'talent':
      s.label = rec.getString('stage_name');
      break;
    case 'character':
    case 'product':
      s.label = rec.getString('name');
      break;
    case 'case':
      s.label = rec.getString('ref') || rec.getString('title');
      break;
    case 'recordation':
      s.jurisdiction = rec.getString('jurisdiction').toUpperCase();
      s.label = rec.getString('right_desc') || rec.getString('application_no');
      break;
    case 'claim':
      s.label = rec.getString('video_title') || rec.getString('video_url');
      break;
    case 'committee':
      s.label = rec.getString('name');
      break;
    default:
      s.label = rec.getString('title') || rec.getString('name') || rec.id;
  }
  return s;
}

