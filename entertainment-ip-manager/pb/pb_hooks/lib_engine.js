function deadlineKey(rule, subject, cycle, baseDate) {
  return 'rule:' + rule.code + ':' + subject.type + ':' + subject.id + ':' + (rule.every > 0 ? 'c' + cycle : baseDate);
}

function existingKeys(app, subject) {
  const u = require(`${__hooks}/lib_util.js`);
  const map = {};
  const rows = u.findMany(app, 'deadlines', SUBJECTS[subject.type].field + ' = {:id}', '', 0, { id: subject.id });
  for (const r of rows) {
    const k = r.getString('key');
    if (k) map[k] = r.getString('status');
  }
  return map;
}

function expiryOf(app, subject) {
  const u = require(`${__hooks}/lib_util.js`);
  if (subject.type !== 'matter') return '';
  return u.d10(subject.record.getString('expiry_date'));
}

/**
 * Deadlines a new event would create. Nothing is written.
 * event: { code, date, data }
 */
function proposalsFor(app, subject, event, opts) {
  const u = require(`${__hooks}/lib_util.js`);
  const o = opts || {};
  const eventDate = u.d10(event.date);
  const data = event.data || {};
  const buffer = Number(u.setting(app, 'target_buffer_days', 14)) || 0;
  const todayD = u.today();
  const rules = candidateRules(app, event.code);
  const events = subjectEvents(app, subject);
  const keys = existingKeys(app, subject);
  const expiry = expiryOf(app, subject);
  const out = [];
  for (const rule of rules) {
    if (!ruleMatches(app, rule, subject, eventDate, events, data)) continue;
    if (Array.isArray(o.onlyCodes) && o.onlyCodes.length && o.onlyCodes.indexOf(rule.code) < 0) continue;
    const overrides = (data.overrides && data.overrides[rule.code]) || data;
    let cycle = rule.every > 0 ? rule.first : Number((rule.conditions && rule.conditions.cycle) || 0);
    let calc = null;
    if (rule.every > 0) {
      let found = false;
      const baseStart = resolveBase(rule, subject, eventDate).date;
      const limit = rule.until > 0 && baseStart !== '' ? u.addYMD(baseStart, rule.until, 0, 0) : '';
      for (let n = rule.first; n < rule.first + 200; n++) {
        const c = computeRule(app, rule, subject, eventDate, n, overrides, buffer, data);
        if (c === null) break;
        if (limit !== '' && c.due > limit) break;
        if (rule.conditions && rule.conditions.stop_at_expiry && expiry !== '' && c.due > expiry) break;
        const stillOpen = (c.grace_end || c.due) >= todayD;
        if (c.due >= eventDate && stillOpen) {
          cycle = n;
          calc = c;
          found = true;
          break;
        }
      }
      if (!found) continue;
    } else {
      calc = computeRule(app, rule, subject, eventDate, cycle, overrides, buffer, data);
      if (calc === null) continue;
    }
    const key = deadlineKey(rule, subject, cycle, calc.base_date);
    const past = (calc.final || calc.grace_end || calc.due) < todayD;
    const exists = Object.prototype.hasOwnProperty.call(keys, key);
    const title = cycleTitle(rule, cycle);
    out.push({
      rule_id: rule.id,
      rule_code: rule.code,
      rule_name: rule.name,
      rule_name_ja: rule.name_ja,
      title: title.en,
      title_ja: title.ja,
      cycle_label: cycleLabel(rule, cycle),
      kind: rule.kind,
      category: rule.category,
      cycle: cycle,
      base_date: calc.base_date,
      nominal_date: calc.nominal,
      due_date: calc.due,
      target_date: calc.target,
      final_date: calc.final,
      window_opens: calc.window_opens,
      grace_end: calc.grace_end,
      office: calc.office,
      citation: rule.citation,
      notes: rule.notes,
      steps: calc.steps,
      key: key,
      past: past,
      exists: exists,
      selected: !past && !exists,
      creates_renewal: rule.creates_renewal,
      fee_kind: rule.fee_kind,
      extensions: rule.extensions,
      business: rule.business,
      overrides: overrides,
    });
  }
  out.sort(function (a, b) {
    return a.due_date < b.due_date ? -1 : a.due_date > b.due_date ? 1 : 0;
  });
  return out;
}

function defaultAssignee(subject) {
  if (!subject || !subject.record) return '';
  const rec = subject.record;
  for (const f of ['responsible', 'docketer', 'assignee']) {
    try {
      const v = rec.getString(f);
      if (v) return v;
    } catch {
      /* field absent */
    }
  }
  if (subject.type === 'talent') {
    try {
      const m = rec.getStringSlice('managers') || [];
      if (m.length) return String(m[0]);
    } catch {
      /* none */
    }
  }
  return '';
}

function denorm(subject) {
  const rec = subject.record;
  const out = {
    jurisdiction: subject.jurisdiction === '*' ? '' : subject.jurisdiction,
    subject_type: subject.subject_type,
    ref: '',
    subject_label: subject.label,
    family: '',
  };
  try {
    out.ref = rec.getString('ref') || '';
  } catch {
    out.ref = '';
  }
  if (subject.type === 'matter') out.family = rec.getString('family');
  return out;
}

/** Create deadline records for selected proposals. Returns created records. */
function commit(app, subject, eventRec, proposals, actorId, source) {
  const u = require(`${__hooks}/lib_util.js`);
  const created = [];
  const keys = existingKeys(app, subject);
  const dn = denorm(subject);
  for (const p of proposals) {
    if (p.selected === false) continue;
    if (Object.prototype.hasOwnProperty.call(keys, p.key)) continue;
    const data = {
      title: p.title,
      title_ja: p.title_ja || p.title,
      kind: p.kind,
      category: p.category,
      status: 'open',
      target_date: u.toPb(p.target_date),
      due_date: u.toPb(p.due_date),
      final_date: u.toPb(p.final_date),
      window_opens: u.toPb(p.window_opens),
      grace_end: u.toPb(p.grace_end),
      nominal_date: u.toPb(p.nominal_date),
      base_date: u.toPb(p.base_date),
      source: source || (p.category === 'playbook' ? 'playbook' : 'rule'),
      rule: p.rule_id || '',
      rule_code: p.rule_code || '',
      base_event: eventRec ? eventRec.id : '',
      calculation: {
        steps: p.steps,
        rule_code: p.rule_code,
        base_date: p.base_date,
        nominal: p.nominal_date,
        office: p.office || '',
        business: p.business === true,
        overrides: p.overrides || {},
        computed_at: u.nowIso(),
      },
      locked: false,
      extension_level: 0,
      cycle: p.cycle || 0,
      key: p.key,
      citation: p.citation || '',
      notes: p.notes || '',
      assignee: p.assignee || defaultAssignee(subject),
      jurisdiction: dn.jurisdiction,
      subject_type: dn.subject_type,
      ref: dn.ref,
      subject_label: dn.subject_label,
      family: dn.family,
      reminders_sent: [],
    };
    data[SUBJECTS[subject.type].field] = subject.id;
    const rec = u.newRecord(app, 'deadlines', data);
    app.save(rec);
    keys[p.key] = 'open';
    created.push(rec);
    if (p.creates_renewal) ensureRenewal(app, rec);
  }
  if (created.length) {
    u.audit(
      app,
      actorId,
      'generate',
      'deadlines',
      subject.id,
      subject.label,
      {
        created: created.map(function (r) {
          return { id: r.id, title: r.getString('title'), due: r.getString('due_date').slice(0, 10) };
        }),
      },
      eventRec ? 'From event ' + eventRec.getString('code') + ' on ' + eventRec.getString('date').slice(0, 10) : '',
    );
  }
  return created;
}

/** Apply an event's status/date effect to its subject. */
function applyEventToSubject(app, subject, code, date) {
  const u = require(`${__hooks}/lib_util.js`);
  const def = EVENT_CODES[code];
  if (!def) return false;
  const rec = subject.record;
  let changed = false;
  if (subject.type === 'matter') {
    if (def.field && u.d10(rec.getString(def.field)) === '' && u.d10(date) !== '') {
      rec.set(def.field, u.toPb(date));
      changed = true;
    }
    if (def.status) {
      const cur = rec.getString('status');
      // Never resurrect a dead matter from a stale event, never regress a live one.
      const curGroup = statusGroup(cur);
      const nextGroup = statusGroup(def.status);
      const regress = curGroup === 'live' && nextGroup === 'pending';
      if (cur !== def.status && !(curGroup === 'dead' && nextGroup !== 'dead') && !regress) {
        rec.set('status', def.status);
        rec.set('status_date', u.toPb(date));
        changed = true;
      }
    }
  } else if (subject.type === 'talent' && def.status) {
    if (rec.getString('lifecycle') !== def.status) {
      rec.set('lifecycle', def.status);
      changed = true;
    }
    if (code === 'GRADUATED' && u.d10(rec.getString('graduation_date')) === '') {
      rec.set('graduation_date', u.toPb(date));
      changed = true;
    }
    if (code === 'DEBUTED' && u.d10(rec.getString('debut_date')) === '') {
      rec.set('debut_date', u.toPb(date));
      changed = true;
    }
  } else if ((subject.type === 'claim' || subject.type === 'case' || subject.type === 'recordation') && def.status) {
    if (rec.getString('status') !== def.status) {
      rec.set('status', def.status);
      changed = true;
    }
    if (subject.type === 'claim' && code === 'CID_DISPUTE_RECEIVED' && u.d10(rec.getString('dispute_received')) === '') rec.set('dispute_received', u.toPb(date));
    if (subject.type === 'claim' && code === 'CID_APPEAL_RECEIVED' && u.d10(rec.getString('appeal_received')) === '') rec.set('appeal_received', u.toPb(date));
    if (subject.type === 'case' && code === 'PLATFORM_REQUEST_SENT' && u.d10(rec.getString('request_sent')) === '') rec.set('request_sent', u.toPb(date));
    if (subject.type === 'case' && code === 'COUNTER_NOTICE_RECEIVED' && u.d10(rec.getString('counter_notice_date')) === '') rec.set('counter_notice_date', u.toPb(date));
    if (subject.type === 'recordation' && code === 'RECORDATION_ACCEPTED' && u.d10(rec.getString('accepted_date')) === '') rec.set('accepted_date', u.toPb(date));
  }
  if (changed) app.save(rec);
  return changed;
}

/**
 * Record an event and (optionally) create its deadlines.
 * opts: { data, label, source, actorId, documentId, commit: bool, select: [keys], skip: [keys] }
 */
function recordEvent(app, subject, code, date, opts) {
  const u = require(`${__hooks}/lib_util.js`);
  const o = opts || {};
  const lbl = eventLabel(code);
  const eventData = {
    code: code,
    label: o.label || lbl.en,
    label_ja: o.label_ja || o.label || lbl.ja,
    date: u.toPb(date),
    source: o.source || 'manual',
    document: o.documentId || '',
    data: o.data || {},
    created_by: o.actorId || '',
  };
  eventData[SUBJECTS[subject.type].field] = subject.id;
  const ev = u.newRecord(app, 'events', eventData);
  app.save(ev);
  if (applyEventToSubject(app, subject, code, date)) {
    subject.record = u.byId(app, SUBJECTS[subject.type].coll, subject.id) || subject.record;
  }
  const proposals = proposalsFor(app, subject, { code: code, date: date, data: o.data || {} });
  if (Array.isArray(o.select)) {
    for (const p of proposals) p.selected = o.select.indexOf(p.key) >= 0 || o.select.indexOf(p.rule_code) >= 0;
  }
  if (Array.isArray(o.skip)) {
    for (const p of proposals) if (o.skip.indexOf(p.key) >= 0 || o.skip.indexOf(p.rule_code) >= 0) p.selected = false;
  }
  if (Array.isArray(o.assignees)) {
    for (const p of proposals) {
      for (const a of o.assignees) if (a && (a.key === p.key || a.rule_code === p.rule_code)) p.assignee = a.assignee || '';
    }
  }
  let created = [];
  if (o.commit !== false) created = commit(app, subject, ev, proposals, o.actorId, o.deadlineSource);
  u.audit(app, o.actorId, 'event', 'events', ev.id, subject.label + ': ' + eventData.label, { code: code, date: u.d10(date) }, '');
  if (subject.type === 'matter') refreshMatterSummary(app, subject.id);
  return { event: ev, proposals: proposals, created: created };
}

/** Make sure a system event exists for (subject, code) at `date`; move it and regenerate if the date changed. */
function ensureSystemEvent(app, subject, code, date, actorId, data) {
  const u = require(`${__hooks}/lib_util.js`);
  if (u.d10(date) === '') return { created: 0, moved: 0 };
  const evs = u.findMany(app, 'events', SUBJECTS[subject.type].field + ' = {:id} && code = {:c}', '-created', 0, { id: subject.id, c: code });
  if (evs.length === 0) {
    const r = recordEvent(app, subject, code, date, { source: 'system', actorId: actorId, data: data || {} });
    return { created: r.created.length, moved: 0 };
  }
  if (u.d10(evs[0].getString('date')) !== u.d10(date)) {
    evs[0].set('date', u.toPb(date));
    app.save(evs[0]);
    const r = regenerate(app, subject, true, actorId);
    return { created: 0, moved: r.moved.length };
  }
  return { created: 0, moved: 0 };
}

