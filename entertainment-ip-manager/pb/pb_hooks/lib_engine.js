/**
 * The deadline engine. One engine for every dated obligation that follows an
 * event: trademark and design prosecution and renewals, copyright
 * registration and termination windows, talent playbooks, Content ID
 * clocks, enforcement and customs periods.
 *
 * Principles:
 * - rules are data (collection `rules`), versioned by effective date;
 * - calendar-month arithmetic, never day counts; business-day offsets count
 *   the office's working days (lib_calendar.addBusinessDays);
 * - closure-day roll-forward by the office where the act is due;
 * - every computed date carries its bilingual explanation (calculation.steps,
 *   each { en, ja }) and citation, so the UI can answer "Why this date?";
 * - preview before creating, diff before regenerating, never duplicate
 *   (deadlines carry a stable `key`), never delete (close with a reason);
 * - a person can lock a date; locked dates are never recomputed.
 *
 * Obligations that come from a record's own fields (agreement terms,
 * committee calendars, product sales windows, approval SLAs, permission
 * expiries) are generated by lib_obligations.js, not by rules.
 */

