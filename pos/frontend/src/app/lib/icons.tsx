export const ICON_NAMES = Object.keys(CATEGORY_ICONS);

export function iconFor(name: string): LucideIcon {
  return CATEGORY_ICONS[name] ?? Tag;
}

/** The token names of a category color slot (0 = no category). */
export function catVars(slot: number): { mark: string; soft: string; text: string } {
  const n = slot >= 1 && slot <= 8 ? slot : 0;
  return { mark: `var(--ps-cat-${n})`, soft: `var(--ps-cat-${n}-soft)`, text: `var(--ps-cat-${n}-text)` };
}
