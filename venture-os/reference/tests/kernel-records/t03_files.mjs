section('upload, the text step on a real PDF, needs_ocr on a picture page');
await api.op('testkit.events', { clear: true }, O);
const up = await upload(api, 'files.upload', { deal: d.number, folder: 'Pitch' }, [{ name: 'Acme deck.pdf', bytes: pdf }], 'owner');
ok(up.status === 200 && up.body.files.length === 1, 'a person uploads a PDF to the deal room', up.body);
const f1 = up.body.files[0];
ok(['waiting', 'extracting'].indexOf(f1.text_state) >= 0, 'the answer comes before the text is read (state ' + f1.text_state + ')');
ok(typeof up.body._activity === 'string' && up.body._activity !== '', 'the upload is one activity unit');
eq(f1.folder, 'Pitch', 'folder kept');
const g1 = await waitText(api, f1.id, 'owner');
eq(g1.file.text_state, 'ready', 'the text step ended: ready');
eq(g1.file.pages, 2, 'two pages');
eq(g1.file.sha256, sha, 'sha256 of the stored bytes');
eq(g1.needs_ocr, [2], 'the picture page needs OCR, the text page does not');
const txt = await api.op('files.text', { file: f1.id }, O);
const p1 = txt.pages.filter((p) => p.page === 1)[0];
ok(p1 && p1.lines.some((l) => l[3] === DECK_LINES[0]) && p1.lines.some((l) => l[3] === DECK_LINES[2]), 'files.text gives the deck\'s lines', p1);
const added = await ev('file.added');
const ready = await ev('file.text_ready');
ok(added.length === 1 && added[0].payload.file === f1.id && added[0].payload.owner_collection === 'deals', 'file.added { file, owner_collection, owner_id }', added);
ok(ready.length === 1 && ready[0].payload.file === f1.id && ready[0].payload.text_state === 'ready' && ready[0].payload.ocr_pages[0] === 2, 'file.text_ready { file, text_state, ocr_pages }', ready);
const pg = await api.op('pages.get', { file: f1.id, from: 1, to: 2 }, O);
ok(pg.pages[0].items.length >= 3 && pg.pages[0].width === 612, 'pages.get gives positioned items for the reader');

