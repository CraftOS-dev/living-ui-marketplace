section('OCR and anchors');
const ocr = await api.op('pages.set-ocr', { file: f1.id, page: 2, words: [{ text: 'Revenue', x0: 72, top: 400, x1: 130, bottom: 412 }, { text: 'chart', x0: 135, top: 400, x1: 170, bottom: 412 }, { text: 'FY2025', x0: 72, top: 420, x1: 120, bottom: 432 }] }, A);
ok(ocr.lines === 2 && ocr.pages_needing_ocr === 0, 'your AI agent\'s reading became page 2\'s text');
eq((await api.op('files.get', { file: f1.id }, O)).needs_ocr, [], 'no page needs OCR now');
const a1 = (await api.op('anchors.create', { file: f1.id, page: 1, lines: '2' }, A)).anchor;
eq(a1.quote, DECK_LINES[1], 'an anchor by line number quotes the line');
ok(a1.rects.length === 1 && a1.rects[0][2] > 0, 'with its rectangle on the page');
const a2 = (await api.op('anchors.create', { file: f1.id, quote: 'growing 15 percent' }, A)).anchor;
ok(a2.page === 1 && a2.quote === 'growing 15 percent', 'an anchor by quote finds its page');
const a3 = (await api.op('anchors.create', { file: f1.id, page: 2, quote: 'Revenue chart' }, A)).anchor;
eq(a3.page, 2, 'an anchor on the OCR text');
eq((await api.op('anchors.create', { file: f1.id, page: 1, lines: '2' }, O)).anchor.id, a1.id, 'the same passage gives the same anchor');
await refuses(api, 'anchors.create', { file: f1.id, page: 1, quote: 'not in the deck' }, A, 400, 'quote_not_found', 'a quote that is not on the page is refused');
const ma = (await api.op('anchors.create', { message_id: 'msg-123', ref_collection: 'intake_items', ref_id: 'abc', start: 0, end: 12, quote: 'We raise 3M', deal: d.number }, A)).anchor;
eq(ma.kind, 'message', 'a message anchor');
const rs = await api.op('anchors.resolve', { anchors: [a1.id, a3.id, ma.id, 'missing00000000'], deal: d.number }, O);
const byId = {};
for (const x of rs.anchors) byId[x.id] = x;
ok(byId[a1.id].ok && byId[a1.id].valid === true && byId[a1.id].in_scope === true, 'a deal file anchor resolves, valid and in scope');
ok(byId[a3.id].ok && byId[a3.id].valid === true, 'the OCR anchor resolves');
ok(byId[ma.id].ok && byId[ma.id].valid === null && byId[ma.id].in_scope === true, 'the message anchor resolves (valid unknown: its text lives in another module)');
ok(byId.missing00000000.ok === false && byId.missing00000000.reason === 'missing', 'a missing anchor says so');
const rs2 = await api.op('anchors.resolve', { anchor: a1.id, deal: d2.number }, O);
eq(rs2.anchors[0].in_scope, false, 'another deal may not cite it (citation scope)');

