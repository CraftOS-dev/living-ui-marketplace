// Sign-in, invites, lockout, the approval PIN, owner recovery, members, roles
// and fund scope, with your AI agent refused before any param or PIN check.
import { DEMO, PORT, eq, fresh, newApi, ok, refuses, section, setupFirm, summary } from './lib.mjs';

fresh();
const api = newApi();
const setup = await setupFirm(api);
let recovery = setup.recovery_code;
const O = { as: 'owner' };
const OP = { as: 'owner', pin: true };

section('login and lockout');
await refuses(api, 'auth.login', { email: DEMO.owner, password: 'wrong-pass' }, { as: 'anon' }, 401, 'wrong_password', 'wrong password');
await refuses(api, 'auth.login', { email: 'nobody@x.test', password: 'whatever1' }, { as: 'anon' }, 401, 'wrong_password', 'unknown email answers the same');
const inv = await api.op('members.invite', { email: 'lock@venture.test', name: 'Lee Lock', role: 'analyst' }, OP);
ok(/^[A-Z0-9]{5}-[A-Z0-9]{5}$/.test(inv.code), 'invite code in groups of 5 (XXXXX-XXXXX)', inv.code);
ok(Date.parse(inv.expires) - Date.now() > 6.9 * 86400000 && Date.parse(inv.expires) - Date.now() < 7.1 * 86400000, 'invite valid 7 days');
await refuses(api, 'auth.login', { email: 'lock@venture.test', password: 'anything1' }, { as: 'anon' }, 401, 'wrong_password', 'an invited member cannot sign in before accepting');
await refuses(api, 'auth.accept-invite', { email: 'lock@venture.test', code: 'AAAAA-BBBBB', password: DEMO.password }, { as: 'anon' }, 400, 'bad_invite', 'wrong invite code');
const acc = await api.op('auth.accept-invite', { email: 'lock@venture.test', code: inv.code.toLowerCase().replace('-', ' '), password: DEMO.password });
ok(acc.token && acc.me.member.email === 'lock@venture.test' && acc.me.role.code === 'analyst', 'accepted the invite (code case and separator free) and signed in');
await refuses(api, 'auth.accept-invite', { email: 'lock@venture.test', code: inv.code, password: DEMO.password }, { as: 'anon' }, 400, 'bad_invite', 'an invite code works once');
const st9 = [];
for (let i = 0; i < 9; i++) st9.push((await api.call('auth.login', { email: 'lock@venture.test', password: 'wrong-' + i })).status);
eq(st9, [401, 401, 401, 401, 401, 401, 401, 401, 401], 'nine wrong passwords answer 401');
await refuses(api, 'auth.login', { email: 'lock@venture.test', password: DEMO.password }, { as: 'anon' }, 423, 'locked', 'locked after 10 failures (right password refused)');
const reset = await api.op('members.reset', { member: 'lock@venture.test' }, OP);
ok(reset.code, 'the owner gives a new sign-in code (clears the lock)');
const acc2 = await api.op('auth.accept-invite', { email: 'lock@venture.test', code: reset.code, password: 'new-pass-22' });
ok(acc2.token, 'the member sets a new password with the code');
await api.op('members.disable', { member: 'lock@venture.test' }, OP);
await refuses(api, 'auth.login', { email: 'lock@venture.test', password: 'new-pass-22' }, { as: 'anon' }, 403, 'account_disabled', 'disabled member cannot sign in');
await api.op('members.enable', { member: 'lock@venture.test' }, OP);
const back = await api.call('auth.login', { email: 'lock@venture.test', password: 'new-pass-22' });
eq(back.status, 200, 'enabled member signs in again');
const lockT = 'lock@venture.test';
api.setToken(lockT, back.body.token);
const so = await api.op('members.signout', {}, { as: lockT });
ok(so.token, 'sign out everywhere answers a fresh token for the caller');
const old = await api.call('auth.me', {}, { as: { email: 'x' } }).catch(() => null);
ok(old === null || old.status >= 400, 'a made-up member cannot call');
api.setToken(lockT, so.token);

section('PIN');
await refuses(api, 'members.invite', { email: 'x1@venture.test', name: 'X', role: 'analyst' }, O, 400, 'missing_param', 'confirm op without pin');
await refuses(api, 'members.invite', { email: 'x1@venture.test', name: 'X', role: 'analyst', pin: '000001' }, O, 403, 'wrong_pin', 'wrong PIN refused');
const v1 = await api.op('pin.verify', { pin: '000002' }, O);
eq([v1.ok, v1.code, v1.attempts_left], [false, 'wrong_pin', 3], 'pin.verify answers 200 with attempts left (wrong tries count)');
const v2 = await api.op('pin.verify', { pin: DEMO.pin }, O);
eq(v2.ok, true, 'pin.verify with the right PIN (resets the count)');
await refuses(api, 'pin.change', { current_pin: '123456', new_pin: '654321' }, { as: lockT }, 409, 'pin_not_set', 'a member without a PIN must set one first');
await refuses(api, 'pin.set', { password: 'bad-password', new_pin: '246810' }, { as: lockT }, 400, 'wrong_password', 'setting a PIN needs the password');
await api.op('pin.set', { password: 'new-pass-22', new_pin: '246810' }, { as: lockT });
await refuses(api, 'pin.set', { password: 'new-pass-22', new_pin: '246811' }, { as: lockT }, 409, 'pin_exists', 'pin.set only the first time');
await api.op('pin.change', { current_pin: '246810', new_pin: '135790' }, { as: lockT });
for (let i = 0; i < 4; i++) await api.call('pin.change', { current_pin: '00000' + i, new_pin: '112233' }, { as: lockT });
const fifth = await api.call('pin.change', { current_pin: '000009', new_pin: '112233' }, { as: lockT });
ok(fifth.status === 403 && /locked/.test(fifth.body.message), 'fifth wrong PIN locks it', fifth.body);
await refuses(api, 'pin.change', { current_pin: '135790', new_pin: '112233' }, { as: lockT }, 423, 'pin_locked', 'right PIN refused while locked');
await api.op('pin.reset', { member: lockT }, OP);
eq((await api.op('pin.status', {}, { as: lockT })).has_pin, false, 'the owner cleared the PIN (and the lock)');
await api.op('pin.set', { password: 'new-pass-22', new_pin: '246810' }, { as: lockT });
eq((await api.op('pin.status', {}, { as: lockT })).has_pin, true, 'member set a new PIN');

section('owner recovery');
await refuses(api, 'pin.recover', { recovery_code: 'AAAAA-BBBBB-CCCCC-DDDDD', new_pin: '975310' }, O, 400, 'bad_recovery_code', 'wrong recovery code');
const rec = await api.op('pin.recover', { recovery_code: recovery, new_pin: '975310' }, O);
ok(rec.recovery_code && rec.recovery_code !== recovery, 'PIN reset with the recovery code; a new code is issued');
await refuses(api, 'pin.recover', { recovery_code: recovery, new_pin: '975311' }, O, 400, 'bad_recovery_code', 'the old recovery code no longer works');
recovery = rec.recovery_code;
await refuses(api, 'members.invite', { email: 'x2@venture.test', name: 'X', role: 'analyst', pin: DEMO.pin }, O, 403, 'wrong_pin', 'old PIN refused after recovery');
const rr = await api.op('auth.recover', { email: DEMO.owner, recovery_code: recovery, password: 'recovered-1', new_pin: DEMO.pin });
ok(rr.token && rr.recovery_code !== recovery, 'owner signed in with the recovery code and set a new password and PIN');
api.forget(DEMO.owner);
await refuses(api, 'auth.login', { email: DEMO.owner, password: DEMO.password }, { as: 'anon' }, 401, 'wrong_password', 'old password no longer works');
api.setToken(DEMO.owner, rr.token);
const cp = await api.op('auth.change-password', { current: 'recovered-1', password: DEMO.password }, O);
api.setToken(DEMO.owner, cp.token);
recovery = rr.recovery_code;
const nr = await api.op('pin.recovery-new', {}, OP);
ok(nr.recovery_code && nr.recovery_code !== recovery, 'a new recovery code with the PIN');
recovery = nr.recovery_code;

section('members, roles and scope');
const pInv = await api.op('members.invite', { email: 'partner@venture.test', name: 'Paul Partner', role: 'partner' }, OP);
const pJoin = await api.op('auth.accept-invite', { email: 'partner@venture.test', code: pInv.code, password: DEMO.password });
api.setToken('partner@venture.test', pJoin.token);
await api.op('pin.set', { password: DEMO.password, new_pin: DEMO.pin }, { as: 'partner@venture.test' });
const P = { as: 'partner@venture.test', pin: true };
await refuses(api, 'members.invite', { email: 'own2@venture.test', name: 'O', role: 'owner' }, P, 403, 'not_permitted', 'a partner cannot invite (settings full)');
await refuses(api, 'roles.add', { name: 'Operating partner', levels: { portfolio: 'edit' } }, P, 403, 'not_permitted', 'a partner cannot change roles');
await refuses(api, 'settings.update', { firm_name: 'Hacked' }, { as: 'partner@venture.test' }, 403, 'not_permitted', 'a partner cannot change firm settings');
const pm = await api.call('members.list', {}, { as: 'partner@venture.test' });
eq(pm.status, 200, 'a partner sees the team (settings view)');
await refuses(api, 'members.list', {}, { as: lockT }, 403, 'not_permitted', 'an analyst cannot list members');
const role = await api.op('roles.add', { name: 'Operating partner', levels: { portfolio: 'edit', network: 'edit' }, votes: false }, OP);
eq([role.code, role.levels.portfolio, role.levels.funds], ['operating_partner', 'edit', 'none'], 'owner added a role (code from the name)');
await refuses(api, 'roles.add', { name: 'Bad', levels: { payroll: 'full' } }, OP, 400, 'invalid_param', 'unknown module refused');
await refuses(api, 'roles.update', { role: 'owner', name: 'Boss' }, OP, 409, 'invalid', 'the Owner role cannot change');
await refuses(api, 'roles.delete', { role: 'analyst' }, OP, 409, 'invalid', 'built-in roles stay');
eq((await api.op('roles.delete', { role: 'operating_partner' }, OP)).deleted, true, 'a custom role nobody has can be deleted');
await refuses(api, 'members.disable', { member: DEMO.owner }, OP, 409, 'invalid', 'you cannot disable yourself');
await refuses(api, 'members.update', { member: DEMO.owner, role: 'partner' }, OP, 409, 'last_owner', 'keep one owner');
const fund2 = await api.op('entities.save', { kind: 'fund', name: 'Fund II', currency: 'EUR', vintage: 2027, size: '120000000' }, O);
await api.op('members.update', { member: 'partner@venture.test', funds: JSON.stringify(['Fund II']) }, OP);
const pme = await api.op('auth.me', {}, { as: 'partner@venture.test' });
eq([pme.funds_scope.length, pme.funds.map((f) => f.name)], [1, ['Fund II']], 'a partner limited to Fund II sees only it');
const ple = await api.op('entities.list', {}, { as: 'partner@venture.test' });
eq(ple.entities.map((e) => e.name).sort(), ['Fund II', 'Northwind Ventures'], 'entities.list follows the scope (management company always)');
await refuses(api, 'entities.get', { entity: 'Fund I' }, { as: 'partner@venture.test' }, 404, 'not_found', 'a fund out of scope is not found');
const ome = await api.op('auth.me', {}, O);
eq(ome.funds.length, 2, 'the owner sees every fund');
eq(fund2.entity.size_minor, 12000000000, 'Fund II size in EUR minor units');
await refuses(api, 'members.update', { member: 'partner@venture.test', funds: JSON.stringify(['Northwind Ventures']) }, OP, 400, 'invalid_param', 'the management company is not a fund scope');
const list = await api.op('members.list', {}, O);
ok(list.total >= 3 && list.members.every((m) => m.has_pin !== undefined), 'members list with PIN flag');
const audit = await api.op('audit.list', { op: 'members.invite' }, O);
ok(audit.total >= 2, 'invites are in the audit trail (' + audit.total + ')');
const allAudit = JSON.stringify(await api.op('audit.list', { limit: 500 }, O));
ok(allAudit.indexOf('demo-pass-1') < 0 && allAudit.indexOf('new-pass-22') < 0 && allAudit.indexOf('"123456"') < 0 && allAudit.indexOf(recovery) < 0, 'no password, PIN or recovery code in the audit trail');

section('your AI agent');
eq((await api.call('members.list', {}, { as: 'agent' })).status, 200, 'your AI agent can read the member list');
await refuses(api, 'members.invite', { email: 'a@x.test', name: 'A', role: 'analyst' }, { as: 'agent' }, 403, 'agent_not_permitted', 'your AI agent cannot invite');
const before = await api.call('members.invite', {}, { as: 'agent' });
eq([before.status, before.body.code], [403, 'agent_not_permitted'], 'refused before params (no missing_param)');
const withPin = await api.call('roles.add', { name: 'X', pin: '123456' }, { as: 'agent' });
eq(withPin.body.code, 'agent_not_permitted', 'refused before the PIN check');
await refuses(api, 'members.signout', {}, { as: 'agent' }, 403, 'agent_not_permitted', 'your AI agent cannot sign people out');
await refuses(api, 'exports.all', {}, { as: 'agent' }, 403, 'agent_not_permitted', 'your AI agent cannot export');
await refuses(api, 'settings.autonomy', { autonomy: '{"merges":"auto"}' }, { as: 'agent' }, 403, 'agent_not_permitted', 'your AI agent cannot change its autonomy');
const ame = await api.op('auth.me', {}, { as: 'agent' });
eq([ame.actor, ame.funds.length, ame.fund_data_visible], ['agent', 2, true], 'your AI agent sees all funds and LP data while the switch is on');
await api.op('settings.update', { agent_sees_fund_data: false }, O);
eq((await api.op('auth.me', {}, { as: 'agent' })).fund_data_visible, false, 'switch off: LP data hidden from your AI agent');
const ops = JSON.parse(await (await fetch('http://127.0.0.1:' + PORT + '/api/_ops')).text());
const inviteOp = (ops.operations || []).find((o) => o.name === 'members.invite');
ok(inviteOp && /\[People only\.\]/.test(inviteOp.description) && inviteOp.params.pin === undefined, 'operations.json marks people-only ops and hides their PIN param', inviteOp);

const s = summary('t02_auth');
process.exitCode = s.failed > 0 ? 1 : 0;
