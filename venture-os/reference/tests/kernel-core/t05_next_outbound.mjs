// Next aggregation (a fake module's needsYou, the kernel's items, snoozes,
// actions filtered by rights) and outbound (draft, edit, approve, send
// through the mock bridge, send key, missing attachment, the 200-with-error
// shape, offline, pace) and the mail helpers.
import { bridge, eq, fresh, member, newApi, ok, refuses, section, setupFirm, sleep, summary } from './lib.mjs';

fresh();
const api = newApi();
await setupFirm(api);
await bridge.reset();
const O = { as: 'owner' };
const A = { as: 'agent' };
await member(api, 'partner@venture.test', 'partner', 'Paul Partner');
await member(api, 'analyst@venture.test', 'analyst', 'Ann Analyst');
const PA = { as: 'partner@venture.test' };
const AN = { as: 'analyst@venture.test' };

section('Next aggregation');
const a = (await api.op('zz.make', { name: 'Acme Robotics', value: 3 }, O)).thing;
await api.op('zz.make', { name: 'Lumen Health', value: 2 }, O);
const nx = await api.op('next.list', {}, PA);
const item = nx.items.find((i) => i.key === 'zz:' + a.id);
ok(item, 'the module item is in Next', nx.items.map((i) => i.key));
eq([item.kind, item.card, item.rank, item.module, item.figures[0].label, item.steps.at], ['verdict', 'zz', 20, 'zz_test', 'Value', 2], 'kind, card, rank, module, figures, steps kept');
eq(item.chips.map((c) => c.tone), ['good', 'neutral'], 'an unknown chip tone becomes neutral');
eq(item.actions.map((x) => x.op), ['zz.make'], 'an action the partner may not run (members.invite) is left out');
eq([item.actions[0].done, item.actions[0].undo, item.actions[0].tone], ['Bumped', { op: 'zz.save', params: { thing: a.id, value: 3 } }, 'good'], 'action fields done, undo and tone pass through');
const own = (await api.op('next.list', {}, O)).items.find((i) => i.key === 'zz:' + a.id);
eq(own.actions.map((x) => [x.op, x.pin]), [['zz.make', false], ['members.invite', true]], 'the owner keeps it, marked as needing the PIN');
eq(own.actions[1].tone, 'neutral', 'an unknown action tone becomes neutral');
ok(nx.errors.some((e) => e.key === 'zz:bad' && /kind/.test(e.error)) && nx.errors.some((e) => /duplicate/.test(e.error)), 'bad kinds and duplicate keys are reported, never a 5xx', nx.errors);
const keys = nx.items.map((i) => i.rank);
ok(keys.every((r, i) => i === 0 || keys[i - 1] <= r), 'sorted by rank');
const cnt = await api.op('next.count', {}, PA);
eq(cnt.total, nx.total, 'next.count agrees');
const page1 = await api.op('next.list', { limit: 1 }, PA);
ok(page1.items.length === 1 && page1.next_cursor === '1', 'paged by cursor', page1.next_cursor);
const act = await api.op(item.actions[0].op, item.actions[0].params, PA);
ok(act.thing && act.thing.name === 'Acme Robotics+', 'an item action runs its op', act);

section('snooze');
await refuses(api, 'next.snooze', { key: item.key }, A, 403, 'agent_not_permitted', 'your AI agent has no Next to snooze');
const sz = await api.op('next.snooze', { key: item.key, hours: 2 }, PA);
ok(Date.parse(sz.until) > Date.now() + 1.9 * 3600000, 'snoozed for two hours');
const nx2 = await api.op('next.list', {}, PA);
ok(!nx2.items.some((i) => i.key === item.key) && nx2.snoozed === 1, 'the snoozed item is hidden and counted');
ok((await api.op('next.list', {}, O)).items.some((i) => i.key === item.key), 'snoozes are per person');
await api.op('next.snooze', { key: item.key, until: '' }, PA);
ok((await api.op('next.list', {}, PA)).items.some((i) => i.key === item.key), 'until "" brings it back');
const tomorrow = await api.op('next.snooze', { key: item.key }, PA);
ok(Date.parse(tomorrow.until) > Date.now(), 'default: until tomorrow 08:00', tomorrow);

section('tasks in Next');
const today = (await api.op('app.today', {}, PA)).today;
const tk = await api.op('tasks.save', { title: 'Call Maya', due_day: today, assignee: 'partner@venture.test' }, O);
const tn = (await api.op('next.list', { kinds: 'task' }, PA)).items.find((i) => i.key === 'kernel:task:' + tk.task.id);
ok(tn && tn.actions[0].op === 'tasks.complete', 'a task due today is in its owner Next', tn);
const snz = tn.actions.find((x) => x.op === 'next.snooze');
ok(snz && snz.label === 'Snooze' && snz.params.key === tn.key && snz.undo && snz.undo.params.until === '', 'task items offer Snooze beside Done (with its undo)', tn.actions);
await api.op(snz.op, snz.params, PA);
ok(!(await api.op('next.list', { kinds: 'task' }, PA)).items.some((i) => i.key === tn.key), 'snoozed: the task leaves Next');
await api.op(snz.undo.op, snz.undo.params, PA);
ok((await api.op('next.list', { kinds: 'task' }, PA)).items.some((i) => i.key === tn.key), 'its undo brings it back');
await api.op('tasks.complete', { task: tk.task.id }, PA);
ok(!(await api.op('next.list', { kinds: 'task' }, PA)).items.some((i) => i.key === 'kernel:task:' + tk.task.id), 'done: it leaves Next');
const agentTask = await api.op('tasks.save', { title: 'Send the data room list', assignee: 'partner@venture.test', due_day: today }, A);
eq([agentTask.task.source, agentTask.task.actor], ['agent', 'agent'], 'your AI agent opens a task for a stated next step');
await refuses(api, 'tasks.complete', { task: agentTask.task.id }, A, 403, 'agent_not_permitted', "completing a person's task is people only");
await refuses(api, 'tasks.save', { task: tk.task.id, title: 'Changed' }, A, 403, 'not_permitted', "your AI agent does not change a person's task");

section('outbound: draft, edit, approve, send');
const f1 = (await api.op('zz.file', { name: 'memo.pdf', text: '%PDF-1.4 sample memo' }, O)).file;
const d1 = await api.op('outbound.draft', { kind: 'reply', module: 'intake', to: '["maya@acmerobotics.ai"]', subject: 'Acme Robotics: our decision', body: 'Dear Maya,\n\nThank you for sharing Acme. What we liked: the traction. What would change our view: a lead investor.\n\nBest', attachments: JSON.stringify([f1.id]) }, A);
eq([d1.status, d1.actor, d1.ai_chars > 50, d1.typed_chars], ['draft', 'agent', true, 0], 'your AI agent drafts; the text counts as AI-written');
ok(/^snd_[a-z0-9]{24}$/.test(d1.send_key), 'one send key per message');
const dn = (await api.op('next.list', { kinds: 'draft' }, PA)).items.find((i) => i.key === 'kernel:outbound:' + d1.id);
ok(dn && dn.card === 'draft' && dn.data.body.indexOf('Dear Maya') === 0 && dn.actions[0].op === 'outbound.approve', 'the draft is in Next with its full text and Approve and send', dn);
eq([dn.data.edit.op, dn.data.edit.params, dn.data.edit.fields.subject, dn.data.edit.fields.body.indexOf('Dear Maya')], ['outbound.update', { outbound: d1.id }, 'Acme Robotics: our decision', 0], 'data.edit: the op and fields to edit the draft in Focus');
const viaEdit = await api.op(dn.data.edit.op, Object.assign({}, dn.data.edit.params, { subject: 'Acme Robotics: our decision' }), PA);
eq(viaEdit.status, 'draft', 'the edit op runs with its params');
ok((await api.op('next.list', { kinds: 'draft' }, AN)).items.some((i) => i.key === 'kernel:outbound:' + d1.id), 'an analyst (intake edit) may approve an intake draft too');
const fd = await api.op('outbound.draft', { kind: 'notice', module: 'funds', to: '["lp@pension.org"]', subject: 'Capital call', body: 'Notice' }, O);
ok(!(await api.op('next.list', { kinds: 'draft' }, PA)).items.some((i) => i.key === 'kernel:outbound:' + fd.id), 'a funds draft is not in the partner Next (funds view only)');
await api.op('outbound.cancel', { outbound: fd.id }, O);
const up = await api.op('outbound.update', { outbound: d1.id, body: 'Dear Maya,\n\nThank you for sharing Acme. What we liked: the traction and the team. What would change our view: a lead investor.\n\nBest' }, PA);
ok(up.typed_chars > 0 && up.ai_chars < d1.ai_chars + 1 && up.ai_share_ppm < 1000000, 'a person edit counts typed characters (AI share drops)', [up.ai_chars, up.typed_chars, up.ai_share_ppm]);
await refuses(api, 'outbound.update', { outbound: d1.id, body: 'mine now' }, A, 403, 'not_permitted', 'your AI agent no longer edits a draft a person touched');
await refuses(api, 'outbound.approve', { outbound: d1.id }, A, 403, 'agent_not_permitted', 'your AI agent never approves or sends');
const sent = await api.op('outbound.approve', { outbound: d1.id }, PA);
eq([sent.status, sent.approved_by !== '', sent.sent_at !== ''], ['sent', true, true], 'approved and sent at once');
const log = await bridge.sent();
eq(log.sent.length, 1, 'the bridge received one message');
eq([log.sent[0].to, log.sent[0].subject, log.sent[0].attached.length, log.sent[0].skipped.length], ['maya@acmerobotics.ai', 'Acme Robotics: our decision', 1, 0], 'with its subject and the attachment file');
await refuses(api, 'outbound.approve', { outbound: d1.id }, PA, 409, 'already_sent', 'approving again never sends twice');
eq((await bridge.sent()).sent.length, 1, 'still one message at the bridge');

section('outbound: refusals and failures');
const f2 = (await api.op('zz.file', { name: 'gone.pdf', text: 'bytes' }, O)).file;
const d2 = await api.op('outbound.draft', { kind: 'intro', module: 'network', to: 'sara@foundry.vc', subject: 'Intro', body: 'Hello', attachments: JSON.stringify([f2.id]) }, PA);
await api.op('zz.rmfile', { file: f2.id }, O);
const miss = await refuses(api, 'outbound.approve', { outbound: d2.id }, PA, 409, 'attachment_missing', 'a missing attachment is refused before sending');
eq(miss.body.data.missing, [f2.id], 'it names the missing file');
eq((await api.op('outbound.get', { outbound: d2.id }, PA)).message.status, 'draft', 'the message stays a draft');
eq((await bridge.sent()).sent.length, 1, 'nothing went to the bridge');
const d3 = await api.op('outbound.draft', { kind: 'request', module: 'portfolio', to: '["bounce@example.com"]', subject: 'Q4 update request', body: 'Please send your Q4 numbers.' }, O);
const r3 = await api.op('outbound.approve', { outbound: d3.id }, O);
eq([r3.status, r3.error], ['failed', 'Failed to send email: invalid To header.'], 'a 200 answer with the error shape is recorded as failed');
const fn = (await api.op('next.list', { kinds: 'draft' }, O)).items.find((i) => i.key === 'kernel:outbound:' + d3.id);
ok(fn && fn.chips.some((c) => c.label === 'Not sent' && c.tone === 'bad') && fn.actions[0].label === 'Send again', 'a failed message is back in Next to send again', fn);
const d4 = await api.op('outbound.draft', { kind: 'digest', module: 'settings', to: 'owner@venture.test', subject: 'Your day', body: 'Two meetings.' }, O);
await bridge.mode('send_gmail', 'offline');
const r4 = await api.op('outbound.approve', { outbound: d4.id }, O);
ok(r4.status === 'failed' && /Connect Gmail in CraftBot/.test(r4.error), 'outside CraftBot (503): failed with the connect message', r4);
await bridge.mode('send_gmail', 'ok');
const r4b = await api.op('outbound.approve', { outbound: d4.id }, O);
eq(r4b.status, 'sent', 'sent once the bridge is back');
await refuses(api, 'outbound.draft', { kind: 'pass', module: 'funds', to: '["x@y.com"]', subject: 's', body: 'b' }, PA, 403, 'not_permitted', 'a partner cannot draft for funds (view only)');
await refuses(api, 'outbound.draft', { kind: 'pass', module: 'intake', to: '["not-an-email"]', subject: 's', body: 'b' }, PA, 400, 'invalid_param', 'bad recipient refused');
const c5 = await api.op('outbound.draft', { kind: 'reply', module: 'intake', to: '["a@b.co"]', subject: 's', body: 'b' }, A);
eq((await api.op('outbound.cancel', { outbound: c5.id }, A)).status, 'cancelled', 'your AI agent cancels its own draft');

section('a scout sees only what it owns');
await member(api, 'scout@venture.test', 'scout', 'Sam Scout');
const SC = { as: 'scout@venture.test' };
const others = await api.op('outbound.list', { status: 'all' }, SC);
eq([others.messages.length, others.hidden > 0], [0, true], 'outbound.list: none of the intake drafts of others (counted as hidden)');
await refuses(api, 'outbound.get', { outbound: d1.id }, SC, 404, 'not_found', 'nor one by id');
ok(!(await api.op('next.list', { kinds: 'draft' }, SC)).items.length, 'no drafts in the scout Next');
const mine = await api.op('outbound.draft', { kind: 'reply', module: 'intake', to: '["founder@new.co"]', subject: 'Thanks', body: 'Sent to the team.' }, SC);
eq((await api.op('outbound.list', { status: 'all' }, SC)).messages.map((m) => m.id), [mine.id], 'its own draft only');
eq((await api.op('proposals.list', { status: 'all' }, SC)).total, 0, 'no proposals');
ok((await api.op('chat.list', { status: 'all' }, SC)).asks.length === 0, 'no questions it did not ask');
ok((await api.op('activity.list', {}, SC)).entries.every((e) => e.member !== '' && e.actor === 'person'), 'activity: its own changes only');
ok((await api.op('tasks.list', { view: 'all', status: 'all' }, SC)).tasks.every((t) => t.assignee === '' || t.member !== ''), 'tasks: its own only');
eq((await api.op('tasks.list', { view: 'all', status: 'all' }, SC)).total, 0, 'no tasks of others');

section('outbound: pace');
await bridge.reset();
const ids = [];
for (let i = 0; i < 22; i++) ids.push((await api.op('outbound.draft', { kind: 'request', module: 'portfolio', to: '["ceo' + i + '@co' + i + '.com"]', subject: 'Request ' + i, body: 'Numbers please' }, O)).id);
const states = [];
for (const id of ids) states.push((await api.op('outbound.approve', { outbound: id }, O)).status);
const allSent = (await api.op('outbound.list', { status: 'sent', limit: 300 }, O)).messages;
const lastMinute = allSent.filter((x) => Date.parse(x.sent_at) > Date.now() - 60000).length;
ok(lastMinute === 20 && states.filter((x) => x === 'approved').length >= 2 && states.filter((x) => x === 'sent').length + states.filter((x) => x === 'approved').length === 22, 'at most 20 sends a minute; the rest wait as approved', { lastMinute, states });
eq((await bridge.sent()).sent.length, states.filter((x) => x === 'sent').length, 'the bridge got exactly the sent ones');

section('mail helpers');
const m = await api.op('zz.mail', {}, O);
ok(m.search.ok && m.search.messages.length === 2, 'search by the deals label (with attachment)', m.search);
ok(m.get.ok && m.get.message.from === 'Maya Chen <maya@acmerobotics.ai>' && m.get.message.attachments.length === 1 && m.get.message.internal_at !== '', 'get: headers, body, attachments', m.get.message);
ok(m.attachment.ok && m.attachment.size > 1000 && /mail/.test(m.attachment.path), 'the attachment saved under pb_data/mail', m.attachment);
eq(m.labels, { deals_label: 'Venture OS/Deals', updates_label: 'Venture OS/Updates' }, 'labels from settings');
const bad = await api.op('zz.mail', { id: 'nope' }, O);
eq([bad.get.ok, bad.get.reason], [false, 'error'], 'an unknown message: the 200-with-error shape is an error');
await bridge.mode('search_gmail', 'offline');
const off = await api.op('zz.mail', {}, O);
eq([off.search.ok, off.search.reason], [false, 'offline'], 'offline answers reason offline');
await bridge.mode('search_gmail', 'error', 'Invalid label');
const er = await api.op('zz.mail', {}, O);
eq([er.search.ok, er.search.error], [false, 'Invalid label'], 'a provider error with its message');
await bridge.mode('search_gmail', 'ok');

const s = summary('t05_next_outbound');
process.exitCode = s.failed > 0 ? 1 : 0;
