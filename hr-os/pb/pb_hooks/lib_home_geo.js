/**
 * [lat, lng] for a country and region code ('US', 'CA'), and where the
 * figure comes from: 'region' or 'country'; null for a country the app has
 * no data for.
 */
function centre(country, region) {
  const c = String(country || '').toUpperCase();
  const r = String(region || '').toUpperCase();
  const reg = REGION[c] && r !== '' ? REGION[c][r] || REGION[c][String(region || '')] : undefined;
  if (reg) return { lat: reg[0], lng: reg[1], source: 'region' };
  const k = COUNTRY[c];
  return k ? { lat: k[0], lng: k[1], source: 'country' } : null;
}

module.exports = { centre: centre, COUNTRY: COUNTRY };
