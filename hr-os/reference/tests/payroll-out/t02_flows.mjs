void nameBytes;
ok(recs.slice(1, 6).some((r) => Buffer.from(r.slice(50, 80)).toString('hex') === wantName.toString('hex')), 'a data record carries the furigana in half-width katakana, space padded to 30');
eq(Number(recs[6].slice(7, 19).toString('latin1')), jx.bank_file.total_minor, 'trailer total equals the stored total');
eq(Number(recs[6].slice(1, 7).toString('latin1')), 5, 'trailer count is 5');
