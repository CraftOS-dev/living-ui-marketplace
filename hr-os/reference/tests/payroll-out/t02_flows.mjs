eq(jd.buf.length, (5 + 3) * 122, 'Zengin: header, 5 data, trailer, end, 120 bytes each with CRLF');
eq(sha(jd.buf), jx.bank_file.hash, 'Zengin hash matches');
const recs = [];
for (let i = 0; i < jd.buf.length; i += 122) recs.push(jd.buf.slice(i, i + 120));
eq(recs.map((r) => String.fromCharCode(r[0])).join(''), '12222289', 'record types 1, 2, 8, 9');
eq(recs[0].slice(1, 3).toString('latin1'), '11', 'salary transfer type 11');
