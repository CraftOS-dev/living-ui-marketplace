// Shared writer: turns a pack (or country) object into a readable CommonJS
// module. Table rows and other small objects go on one line each so the
// files stay reviewable. No dashes outside ASCII hyphen are allowed.
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', 'pb_hooks');

function isSmall(v) {
  if (v === null || typeof v !== 'object') return true;
  const s = JSON.stringify(v);
  return s.length <= 110 && !s.includes('\n');
}

function ser(v, ind) {
  const pad = '  '.repeat(ind);
  const pad1 = '  '.repeat(ind + 1);
  if (v === null || typeof v !== 'object') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    if (isSmall(v) && v.every((x) => x === null || typeof x !== 'object')) return JSON.stringify(v);
    return '[\n' + v.map((x) => pad1 + (isSmall(x) ? oneLine(x) : ser(x, ind + 1))).join(',\n') + '\n' + pad + ']';
  }
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  if (keys.length === 0) return '{}';
  return '{\n' + keys.map((k) => pad1 + keyOf(k) + ': ' + (isSmall(v[k]) ? oneLine(v[k]) : ser(v[k], ind + 1))).join(',\n') + '\n' + pad + '}';
}

function keyOf(k) {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k);
}

function oneLine(v) {
  if (v === null || typeof v !== 'object') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(oneLine).join(', ') + ']';
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  return '{ ' + keys.map((k) => keyOf(k) + ': ' + oneLine(v[k])).join(', ') + ' }';
}

function checkText(file, text) {
  for (const ch of [String.fromCharCode(0x2014), String.fromCharCode(0x2013)]) {
    const i = text.indexOf(ch);
    if (i >= 0) throw new Error(file + ': forbidden dash at ' + i + ': ' + text.slice(Math.max(0, i - 40), i + 40));
  }
}

export function writeModule(rel, header, obj) {
  const file = path.join(OUT, rel);
  const text = '// ' + header.split('\n').join('\n// ') + '\n// Generated by the packs-asia builder; see `sources`, `ship` and `notes` for what is verified.\n\nmodule.exports = ' + ser(obj, 0) + ';\n';
  checkText(rel, text);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, 'utf8');
  return file;
}

export function readJson(rel) {
  const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
  return JSON.parse(fs.readFileSync(path.join(here, rel), 'utf8'));
}

