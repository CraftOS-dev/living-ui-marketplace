const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rec = (id, collection, fields = {}) => ({ id, collection, fields, getString(k) { return String(this.fields[k] ?? ''); }, set(k, v) { this.fields[k] = v; } });
