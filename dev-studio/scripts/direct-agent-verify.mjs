import assert from "node:assert/strict";
import { mkdtemp, readFile, mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ROOT } from "../app/config.mjs";
import { operation, request, base } from "./client.mjs";
import { runSavedCheck } from "./development-client.mjs";
const human = (name, args = {}) => operation(name, args, true);
const claim = id => request(`/api/_a2app/tasks/${id}/claim`, {method:"POST",body:"{}"});
const home = await mkdtemp(join(tmpdir(), "studio-direct-protocol-"));
await human("connector-configure", {provider:"external"});
const project = await human("project-create", {path:join(home,"javascript"),kind:"javascript"});
await human("project-trust", {project:project.id,enabled:true});
const config = (await human("workspace-state")).configs.find(c=>c.project===project.id&&c.kind==="test");
const draft = await human("work-create",{project:project.id,mode:"standalone",title:"Direct protocol verification",goal:"Exercise real isolated protocol lifecycle",criteria:"No launcher dependency; scope and human review retained"});
const started = await human("work-start",{work:draft.id});
assert.equal(started.delivery,"external");
assert.equal((await request(`/api/_a2app/tasks/${started.task}`)).request.capability,"studio-development-external");
assert.equal((await human("connector-control",{action:"status"})).connected,false);
const unauthenticated = await fetch(base+"/api/ops/work-progress",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({work:draft.id,message:"not authorized"})});
assert.equal(unauthenticated.ok,false);
await claim(started.task);
await operation("work-context",{work:draft.id});
await assert.rejects(()=>operation("work-release",{work:draft.id,task:started.task}),/before releasing/);
await operation("work-question",{work:draft.id,question:"Use the retained isolated source?"});
await assert.rejects(()=>human("work-answer",{work:draft.id,answer:"Yes"}),/still finishing/);
await assert.rejects(()=>human("work-release",{work:draft.id,task:started.task}),/connected agent/);
await operation("work-release",{work:draft.id,task:started.task});
const resumed=await human("work-answer",{work:draft.id,answer:"Yes, retain it."});
assert.notEqual(resumed.task,started.task);
await assert.rejects(()=>operation("work-release",{work:draft.id,task:started.task}),/current direct/);
await claim(resumed.task);
const context=await operation("work-context",{work:draft.id});
assert.equal(context.answers.at(-1).answer,"Yes, retain it.");
const before=await operation("file-read",{work:draft.id,path:"main.js"});
await operation("file-write",{work:draft.id,path:"main.js",expected:before.digest,text:before.text+"\nexport const directProtocolVerified = true;\n"});
const run=await runSavedCheck(draft.id,config.id);assert.equal(run.exitCode,0);assert.equal(run.stale,false);
const ready=await operation("work-finish",{work:draft.id,summary:"Protocol fixture: retained source, saved check and review handoff; no provider execution claimed."});
assert.equal(ready.status,"ready");
assert.equal((await request(`/api/_a2app/tasks/${resumed.task}`)).status,"completed");
await assert.rejects(()=>operation("file-write",{work:draft.id,path:"late.txt",create:true,text:"forbidden"}));
await assert.rejects(()=>human("work-revise",{work:draft.id,instruction:"Review retained source again"}),/still finishing/);
await operation("work-release",{work:draft.id,task:resumed.task});
const revision=await human("work-revise",{work:draft.id,instruction:"Recheck retained source without changing behavior"});
await claim(revision.task);
assert.equal((await operation("work-context",{work:draft.id})).isolatedRoot,context.isolatedRoot);
await operation("work-finish",{work:draft.id,summary:"Protocol retained revision verified."});
await operation("work-release",{work:draft.id,task:revision.task});
const applied=await human("review-apply",{work:draft.id,paths:["main.js"]});
assert.deepEqual(applied.conflicts,[]);assert.match(await readFile(join(project.root,"main.js"),"utf8"),/directProtocolVerified/);
